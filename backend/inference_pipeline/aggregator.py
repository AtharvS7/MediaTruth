"""
ConfidenceAggregator — fuses signals from all detectors into a final verdict.

Signal weights (tuned empirically):
  deepfake    → ai_generated (0.40)
  gan         → ai_generated (0.35)
  manipulation → ai_edited / traditional_edit (0.35)
  metadata    → boosts/suppresses all categories (0.20)

BUG-009 fix:
  - authentic is now computed as additive complement:
      authentic = max(0.0, 1.0 - (ai_generated + ai_edited + traditional_edit))
    instead of 1.0 - max(...). This is semantically correct: authentic is what's
    left after all manipulation signals are accounted for.
  - Clamp before computing authentic, then normalise all four together.
"""

import logging
from typing import Any, Dict, List

logger = logging.getLogger(__name__)

VERDICT_LABELS: Dict[str, str] = {
    "ai_generated": "AI Generated",
    "ai_edited": "AI Edited",
    "traditional_edit": "Traditionally Edited",
    "authentic": "Authentic / Original",
}

EXPLANATIONS: Dict[str, str] = {
    "ai_generated": "Multiple detectors indicate this content was fully generated by an AI model (GAN, diffusion model, or similar).",
    "ai_edited": "Evidence suggests portions of this content were modified using AI-powered editing tools.",
    "traditional_edit": "Analysis indicates traditional image editing (Photoshop, Lightroom, etc.) was applied.",
    "authentic": "No significant manipulation signals detected. The content appears to be an original, unedited capture.",
}


class ConfidenceAggregator:
    def aggregate(
        self,
        deepfake: Dict[str, Any],
        gan: Dict[str, Any],
        manipulation: Dict[str, Any],
        metadata: Dict[str, Any],
    ) -> Dict[str, Any]:
        """Aggregate detector scores into a final probability matrix."""

        df_score: float = deepfake.get("score", 0.0)
        gan_score: float = gan.get("score", 0.0)
        manip_score: float = manipulation.get("score", 0.0)
        meta_score: float = metadata.get("anomaly_score", 0.0)

        # ── Base probabilities ────────────────────────────────────────────────
        ai_generated: float = 0.40 * df_score + 0.35 * gan_score + 0.15 * meta_score
        ai_edited: float = 0.35 * manip_score + 0.10 * df_score + 0.15 * meta_score
        traditional_edit: float = 0.45 * manip_score + 0.10 * meta_score

        # Clamp individually before computing authentic
        ai_generated = min(max(ai_generated, 0.0), 1.0)
        ai_edited = min(max(ai_edited, 0.0), 1.0)
        traditional_edit = min(max(traditional_edit, 0.0), 1.0)

        # BUG-009: additive complement — authentic = leftover probability
        authentic: float = max(0.0, 1.0 - (ai_generated + ai_edited + traditional_edit))

        # ── Normalise to sum=1 ────────────────────────────────────────────────
        total: float = ai_generated + ai_edited + traditional_edit + authentic + 1e-8
        ai_generated /= total
        ai_edited /= total
        traditional_edit /= total
        authentic /= total

        # ── Verdict = argmax ──────────────────────────────────────────────────
        scores: Dict[str, float] = {
            "ai_generated": ai_generated,
            "ai_edited": ai_edited,
            "traditional_edit": traditional_edit,
            "authentic": authentic,
        }
        verdict_key: str = max(scores, key=scores.get)  # type: ignore[arg-type]
        confidence: float = scores[verdict_key]

        return {
            "ai_generated": round(ai_generated, 4),
            "ai_edited": round(ai_edited, 4),
            "traditional_edit": round(traditional_edit, 4),
            "authentic": round(authentic, 4),
            "verdict": VERDICT_LABELS[verdict_key],
            "verdict_key": verdict_key,
            "confidence": round(confidence, 4),
            "explanation": EXPLANATIONS[verdict_key],
        }

    def aggregate_video(self, frame_results: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Aggregate per-frame results to video-level verdict (temporal mean)."""
        if not frame_results:
            return self.aggregate({}, {}, {}, {})

        keys: List[str] = [
            "ai_generated_probability",
            "ai_edited_probability",
            "traditional_edit_probability",
            "authentic_probability",
        ]

        averages: Dict[str, float] = {}
        for k in keys:
            vals: List[float] = [f.get(k, 0.0) for f in frame_results]
            averages[k] = sum(vals) / len(vals)

        # Renormalise
        total: float = sum(averages.values()) + 1e-8
        ai_gen: float = averages["ai_generated_probability"] / total
        ai_edit: float = averages["ai_edited_probability"] / total
        trad: float = averages["traditional_edit_probability"] / total
        auth: float = averages["authentic_probability"] / total

        scores: Dict[str, float] = {
            "ai_generated": ai_gen,
            "ai_edited": ai_edit,
            "traditional_edit": trad,
            "authentic": auth,
        }
        verdict_key: str = max(scores, key=scores.get)  # type: ignore[arg-type]
        confidence: float = scores[verdict_key]

        return {
            "ai_generated": round(ai_gen, 4),
            "ai_edited": round(ai_edit, 4),
            "traditional_edit": round(trad, 4),
            "authentic": round(auth, 4),
            "verdict": VERDICT_LABELS[verdict_key],
            "verdict_key": verdict_key,
            "confidence": round(confidence, 4),
            "explanation": EXPLANATIONS[verdict_key],
        }
